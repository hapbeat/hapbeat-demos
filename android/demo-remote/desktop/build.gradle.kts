// scrcpy-server v4.1 (Apache-2.0), as in the Android build: never committed, fetched or taken from tools/quest-mirror, SHA-256 verified.
abstract class PrepareScrcpyServer : DefaultTask() {
    @get:Input abstract val url: Property<String>
    @get:Input abstract val sha256: Property<String>
    @get:Internal abstract val localCandidates: ConfigurableFileCollection
    @get:Internal abstract val downloadCache: RegularFileProperty
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun prepare() {
        val expected = sha256.get()
        val cache = downloadCache.get().asFile
        val found = (localCandidates.files + cache).firstOrNull { it.isFile && digest(it.readBytes()) == expected }
        val bytes = found?.readBytes() ?: run {
            logger.lifecycle("Downloading ${url.get()}")
            val downloaded = URI(url.get()).toURL().openStream().use { it.readBytes() }
            if (digest(downloaded) != expected) throw GradleException("scrcpy-server SHA-256 mismatch")
            cache.parentFile.mkdirs()
            cache.writeBytes(downloaded)
            downloaded
        }
        val out = outputDir.get().asFile
        out.mkdirs()
        out.resolve("scrcpy-server.jar").writeBytes(bytes)
    }

    private fun digest(bytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
}

val prepareScrcpyServer = tasks.register<PrepareScrcpyServer>("prepareScrcpyServer") {
    url.set("https://github.com/Genymobile/scrcpy/releases/download/v4.1/scrcpy-server-v4.1")
    sha256.set("deacb991ed2509715160ffdc7907e47b4160eb30d1566217e9047fd5b8850cae")
    localCandidates.from(repoRoot.resolve("tools/quest-mirror/scrcpy/scrcpy-server"), file("../app/build/scrcpy-download/scrcpy-server-v4.1"))
    downloadCache.set(layout.buildDirectory.file("scrcpy-download/scrcpy-server-v4.1"))
    outputDir.set(layout.buildDirectory.dir("generated/scrcpyResources"))
}

// What the window title shows and the APK folder's default: from git and this checkout, at build time.
val generateBuildInfo = tasks.register("generateBuildInfo") {
    val outputDir = layout.buildDirectory.dir("generated/buildInfo")
    outputs.dir(outputDir)
    outputs.upToDateWhen { false }
    doLast {
        fun literal(text: String) = "\"" + text.replace("\\", "/").replace("\"", "\\\"").replace("$", "\\$") + "\""
        val branch = git("rev-parse", "--abbrev-ref", "HEAD")
        val commit = git("rev-parse", "--short", "HEAD")
        val dirty = git("status", "--porcelain", "--", "android/demo-remote").isNotEmpty()
        val text = listOf(
            "package com.hapbeat.demoremote.desktop",
            "",
            "/** Generated by generateBuildInfo. */",
            "object BuildInfo {",
            "    const val VERSION = ${literal(demoRemoteVersion)}",
            "    const val BRANCH = ${literal(branch)}",
            "    const val COMMIT = ${literal(commit)}",
            "    const val DIRTY = $dirty",
            "    const val DEFAULT_APK_DIR = ${literal(repoRoot.resolve("quest-apks").canonicalPath)}",
            "}",
            "",
        ).joinToString("\n")
        val file = outputDir.get().file("com/hapbeat/demoremote/desktop/BuildInfo.kt").asFile
        file.parentFile.mkdirs()
        if (!file.isFile || file.readText() != text) file.writeText(text)
    }
}

