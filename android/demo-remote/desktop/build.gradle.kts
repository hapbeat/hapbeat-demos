fun git(vararg args: String): String {
    val process = ProcessBuilder(listOf("git", "-C", repoRoot.path) + args).redirectErrorStream(true).start()
    val output = process.inputStream.bufferedReader().readText()
    return if (process.waitFor() == 0) output.trim() else ""
}

/** A JDK 17+ with jpackage: packaging needs one, and Android Studio's JBR (often the Gradle JDK) has none. */
fun findPackagingJdk(): File? {
    val userHome = File(System.getProperty("user.home"))
    val candidates = listOfNotNull(System.getenv("DEMO_REMOTE_JPACKAGE_JDK"), System.getenv("JAVA_HOME"), System.getProperty("java.home")).map { File(it) } +
        userHome.resolve(".gradle/jdks").listFiles().orEmpty().filter { it.isDirectory }.sortedBy { it.name } +
        File("C:/Program Files/Java").listFiles().orEmpty().filter { it.isDirectory }.sortedBy { it.name }
    return candidates.firstOrNull { it.resolve("bin/jpackage.exe").isFile }
}

